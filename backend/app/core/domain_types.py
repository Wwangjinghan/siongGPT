from enum import Enum


class StableStringEnum(str, Enum):
    """String enum whose member values are the public and persisted contract."""


class ScopeType(StableStringEnum):
    COMPANY = "COMPANY"
    DEPARTMENT = "DEPARTMENT"
    PROJECT = "PROJECT"
    PERSONAL_DRAFT = "PERSONAL_DRAFT"


class AccessLevel(StableStringEnum):
    INTERNAL = "INTERNAL"
    RESTRICTED = "RESTRICTED"
    CONFIDENTIAL = "CONFIDENTIAL"


class ResourceAction(StableStringEnum):
    READ = "READ"
    CREATE = "CREATE"
    UPDATE = "UPDATE"
    REVIEW = "REVIEW"
    APPROVE = "APPROVE"
    MANAGE = "MANAGE"


class SourceType(StableStringEnum):
    DOCUMENT = "DOCUMENT"
    EXPERT_NOTE = "EXPERT_NOTE"
    MANUAL_ATTESTATION = "MANUAL_ATTESTATION"


class SourceStatus(StableStringEnum):
    ACTIVE = "ACTIVE"
    ARCHIVED = "ARCHIVED"


class ProcessingStatus(StableStringEnum):
    PENDING = "PENDING"
    PROCESSING = "PROCESSING"
    READY = "READY"
    FAILED = "FAILED"


class PublicationStatus(StableStringEnum):
    DRAFT = "DRAFT"
    PUBLISHED = "PUBLISHED"
    SUPERSEDED = "SUPERSEDED"
    WITHDRAWN = "WITHDRAWN"
    ARCHIVED = "ARCHIVED"


class IngestionJobType(StableStringEnum):
    DOCUMENT_INGESTION = "DOCUMENT_INGESTION"
    DOCUMENT_EMBEDDING = "DOCUMENT_EMBEDDING"


class IngestionJobStatus(StableStringEnum):
    QUEUED = "QUEUED"
    RUNNING = "RUNNING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    DEAD_LETTER = "DEAD_LETTER"
    CANCELLED = "CANCELLED"


class DocumentBlockType(StableStringEnum):
    PARAGRAPH = "PARAGRAPH"
    HEADING = "HEADING"
    TABLE = "TABLE"
    SPREADSHEET_ROWS = "SPREADSHEET_ROWS"


