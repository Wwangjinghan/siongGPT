    ZIP_BOMB_SUSPECTED = "ZIP_BOMB_SUSPECTED"
    MACRO_CONTENT_REJECTED = "MACRO_CONTENT_REJECTED"
    XLSX_LIMIT_EXCEEDED = "XLSX_LIMIT_EXCEEDED"
    EXTRACTED_TEXT_LIMIT_EXCEEDED = "EXTRACTED_TEXT_LIMIT_EXCEEDED"
    PARSER_FAILED = "PARSER_FAILED"
    CHUNKING_FAILED = "CHUNKING_FAILED"
